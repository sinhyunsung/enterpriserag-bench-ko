# 문장만 같아서는 안 되는 이유
#
# 같은 문장을 두 문서에 넣었는데 추출기가 주어·속성을 다르게 잘랐다.
#
#   80억   subject=바로배송 인프라 증설             predicate=약정 계약 규모
#   100억  subject=바로배송 인프라 증설 약정 계약 규모  predicate=규모
#
# 린트는 <b>주어·속성이 같아야</b> 짝으로 본다. 그래서 모순이 한 건도 안 잡혔다.
# `triple` 은 그 셋을 못 박은 것이고, 문서에 아래 한 줄을 같이 넣어 자를 자리를 정해 준다.
#
#   바로배송 인프라 증설 · 약정 계약 규모 = 100억 원
#
# Baton 이 클레임을 그 모양으로 그리므로 추출기가 같은 자리에서 자를 확률이 높다.

def triple_line(triple) -> str:
    """문서에 박을 한 줄. 주어·속성·값을 자를 자리까지 정해 준다."""
    subject, predicate, value = triple
    return f"{subject} · {predicate} = {value}"


