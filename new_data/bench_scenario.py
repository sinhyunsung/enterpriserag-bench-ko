def _topic(word: str) -> str:
    """은/는. 심은 문장은 문서에 글자 그대로 들어가므로 「은(는)」 을 남기면 안 된다."""
    last = word[-1]
    if "가" <= last <= "힣":
        return word + ("은" if (ord(last) - ord("가")) % 28 else "는")
    # 한글이 아니면(영문·숫자) 읽는 소리로 갈린다. 여기 쓰는 속성 이름은 전부 한글이다
    return word + "은"


def _fact(subject: str, predicate: str, value: str) -> str:
    return f"{subject}의 {_topic(predicate)} {value}이다."


